/*
|--------------------------------------------------------------------------
| Names
|--------------------------------------------------------------------------
*/

export const NAME_REGEX =
  /^[A-Za-zÀ-ÖØ-öø-ÿ' -]+$/;

/*
|--------------------------------------------------------------------------
| National ID
|--------------------------------------------------------------------------
*/

export const NATIONAL_ID_REGEX =
  /^[0-9]{6,10}$/;

/*
|--------------------------------------------------------------------------
| KRA PIN
|--------------------------------------------------------------------------
*/

export const KRA_PIN_REGEX =
  /^[A-Z][0-9]{9}[A-Z]$/;

/*
|--------------------------------------------------------------------------
| Phone Number (Kenya)
|--------------------------------------------------------------------------
*/

export const KENYAN_PHONE_REGEX =
  /^(?:\+254|254|0)(7\d{8}|1\d{8})$/;

/*
|--------------------------------------------------------------------------
| Passport
|--------------------------------------------------------------------------
*/

export const PASSPORT_REGEX =
  /^[A-Z0-9]{6,12}$/;

/*
|--------------------------------------------------------------------------
| Postal Code
|--------------------------------------------------------------------------
*/

export const POSTAL_CODE_REGEX =
  /^[0-9]{5}$/;